/** «2026-10-04» → «4 октября 2026 г.». Дата редакции — календарная, часовой пояс ей не нужен. */
export function formatEdition(edition: string): string {
  const match = /^(\d{4})-(\d{2})-(\d{2})$/.exec(edition);
  if (!match) {
    return edition;
  }
  const month = MONTHS_GENITIVE[Number(match[2]) - 1];
  return month ? `${Number(match[3])} ${month} ${match[1]} г.` : edition;
}
