// Общий модуль без "use client": srcset нужен и клиентскому SafeImage, и серверной странице,
// которая объявляет предзагрузку LCP-изображения.

/**
 * Ширины для srcset локальных изображений.
 *
 * Было семь значений — по одному на каждый дефолтный размер Next. Каждый вариант
 * оптимизатор пережимает отдельно и держит в памяти, из-за чего сервер (2 ядра, 2 ГБ)
 * падал с «heap out of memory» при нескольких одновременных посетителях.
 * Четырёх ступеней достаточно, чтобы покрыть телефон, планшет и десктоп с retina,
 * а нагрузка на пережатие падает почти вдвое.
 */
export const RESPONSIVE_WIDTHS = [384, 640, 1080, 1920] as const;

/** srcset через оптимизатор Next: браузер выбирает вариант под свой экран,
 *  вместо того чтобы тянуть оригинал в полторы тысячи пикселей. */
export function buildResponsiveSrcSet(src: string): string {
  return RESPONSIVE_WIDTHS.map(
    (w) => `/_next/image?url=${encodeURIComponent(src)}&w=${w}&q=75 ${w}w`,
  ).join(", ");
}
